"""How often does a substitution between two 3d metals change the sign of its magnetic effect
when the anion set changes from O3 to OFN?

Three O2- and the set O2-, F-, N3- both carry a charge of -6, so at a fixed A site a B-site element
keeps its nominal oxidation state between the two anion sets. For every A-site element and every
unordered pair of the ten 3d metals Sc..Zn, the response to replacing the first metal by the
second is the change in magnetic-moment magnitude (the column the manuscript models), computed
separately in O3 and in OFN. A comparison changes sign when the two responses have opposite signs.
Nothing is fitted: every number is read from the grid.

Writes reports/anion_sign_census.csv (every comparison), reports/anion_sign_series.csv (the
alkaline-earth and La series of the Supporting Information) and reports/AUDIT_ANION_SIGN_CENSUS.md.

Usage:  python3 scripts/run_anion_sign_census.py
"""

from __future__ import annotations

import itertools
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from prfield.report import write_report  # noqa: E402

THREE_D = ["Sc", "Ti", "V", "Cr", "Mn", "Fe", "Co", "Ni", "Cu", "Zn"]
THRESHOLDS = [0.1, 0.2, 0.5]
SERIES = [("Ca", "Mn", "Co"), ("Sr", "Mn", "Co"), ("Ba", "Mn", "Co"),
          ("Ca", "Fe", "Co"), ("Sr", "Fe", "Co"), ("Ba", "Fe", "Co"),
          ("La", "Cr", "Fe"), ("La", "Fe", "Co"), ("La", "Mn", "Co")]
CENSUS = ROOT / "reports/anion_sign_census.csv"
SERIES_CSV = ROOT / "reports/anion_sign_series.csv"
REPORT = ROOT / "reports/AUDIT_ANION_SIGN_CENSUS.md"


def main() -> None:
    grid = pd.read_parquet(ROOT / "data/interim/castelli_raw.parquet")
    moment = grid.assign(m=grid["_magmom"].abs()).set_index(["site_A", "site_B", "site_X"])["m"]
    rows = []
    for a in sorted(grid["site_A"].unique()):
        for b, b2 in itertools.combinations(THREE_D, 2):
            d_o3 = moment[(a, b2, "O3")] - moment[(a, b, "O3")]
            d_ofn = moment[(a, b2, "OFN")] - moment[(a, b, "OFN")]
            rows.append({"A": a, "B": b, "B_prime": b2, "delta_O3": d_o3, "delta_OFN": d_ofn,
                         "sign_change": bool(d_o3 * d_ofn < 0)})
    census = pd.DataFrame(rows)
    census.to_csv(CENSUS, index=False)

    series = []
    for a, b, b2 in SERIES:
        series.append({"A": a, "B": b, "B_prime": b2,
                       "moment_B_O3": moment[(a, b, "O3")], "moment_Bp_O3": moment[(a, b2, "O3")],
                       "moment_B_OFN": moment[(a, b, "OFN")], "moment_Bp_OFN": moment[(a, b2, "OFN")],
                       "delta_O3": moment[(a, b2, "O3")] - moment[(a, b, "O3")],
                       "delta_OFN": moment[(a, b2, "OFN")] - moment[(a, b, "OFN")]})
    series = pd.DataFrame(series)
    series.to_csv(SERIES_CSV, index=False)

    n, k = len(census), int(census["sign_change"].sum())
    out = ["# O3 versus OFN sign census of 3d-metal substitutions\n",
           "Generated by `scripts/run_anion_sign_census.py`. Moments are magnitudes in Bohr magnetons "
           "per cell, read from the grid.\n",
           f"Comparisons: {n:,} ({grid['site_A'].nunique()} A-site elements x "
           f"{len(THREE_D) * (len(THREE_D) - 1) // 2} pairs of 3d metals).\n",
           f"Sign changes: {k:,} ({100 * k / n:.1f}%).\n",
           "| both responses larger than (muB) | sign changes |", "|---|---|"]
    for t in THRESHOLDS:
        big = census["sign_change"] & (census["delta_O3"].abs() > t) & (census["delta_OFN"].abs() > t)
        out.append(f"| {t} | {int(big.sum()):,} |")
    out += ["\n## Series\n", "| A | substitution | O3 | OFN |", "|---|---|---|---|"]
    for r in series.itertuples():
        out.append(f"| {r.A} | {r.B} -> {r.B_prime} | {r.delta_O3:+.3f} | {r.delta_OFN:+.3f} |")
    write_report(REPORT, "\n".join(out))
    print("\n".join(out))
    print("\nwrote " + ", ".join(str(p.relative_to(ROOT)) for p in (CENSUS, SERIES_CSV, REPORT)))


if __name__ == "__main__":
    main()
