"""Per-atom magnetic moments of the Mn, Fe and Co perovskites of Figure 4a.

The Castelli calculations are stored with their per-atom moments in the cubic-perovskite database
of the Computational Materials Repository (data/raw/cmr/cubic_perovskites.db, fetched by
download_data.py). For the A-site elements Ca, Sr, Ba and La, the B-site elements Mn, Fe and Co and
the anion sets O3 and OFN, the script reads the moment on the metal and on each anion, read-only and
without unpickling anything, and records the change in each on replacing Mn or Fe by Co.

Writes reports/cmr_site_moments.csv and reports/AUDIT_CMR_SITE_MOMENTS.md.

Usage:  python3 scripts/run_cmr_site_moments.py
"""

from __future__ import annotations

import sqlite3
import sys
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

from prfield.report import write_report  # noqa: E402

DB = Path("data/raw/cmr/cubic_perovskites.db")
CSV = Path("reports/cmr_site_moments.csv")
REPORT = Path("reports/AUDIT_CMR_SITE_MOMENTS.md")
A_SITES, B_SITES, ANIONS = ("Ca", "Sr", "Ba", "La"), ("Mn", "Fe", "Co"), ("O3", "OFN")
SYMBOL = {7: "N", 8: "O", 9: "F"}


def read_moments() -> pd.DataFrame:
    con = sqlite3.connect(f"file:{DB}?mode=ro", uri=True)
    cur = con.cursor()
    rows = []
    for a in A_SITES:
        for b in B_SITES:
            for x in ANIONS:
                hit = cur.execute(
                    "select s.numbers, s.magmoms from systems s "
                    "join text_key_values ka on ka.id = s.id and ka.key = 'A_ion' and ka.value = ? "
                    "join text_key_values kb on kb.id = s.id and kb.key = 'B_ion' and kb.value = ? "
                    "join text_key_values kx on kx.id = s.id and kx.key = 'anion' and kx.value = ?",
                    (a, b, x)).fetchall()
                if len(hit) != 1 or hit[0][1] is None:
                    continue
                numbers = np.frombuffer(hit[0][0], dtype=np.int32)
                moments = np.frombuffer(hit[0][1], dtype=np.float64)
                rec = {"A": a, "B": b, "X": x, "total": float(moments.sum()),
                       "metal": float(moments[numbers == {"Mn": 25, "Fe": 26, "Co": 27}[b]].sum()),
                       "A_site": float(moments[numbers == numbers[0]].sum())}
                for z, name in SYMBOL.items():
                    rec[name] = float(moments[numbers == z].sum())
                rec["anions"] = rec["N"] + rec["O"] + rec["F"]
                rows.append(rec)
    return pd.DataFrame(rows)


def main() -> None:
    m = read_moments()
    m.to_csv(CSV, index=False)
    lines = ["# Per-atom magnetic moments of the Mn, Fe and Co perovskites\n",
             "Generated by `scripts/run_cmr_site_moments.py` from the CMR cubic-perovskite database. Moments in "
             "Bohr magnetons per cell; `anions` sums the N, O and F moments.\n",
             "| A | B | anions | metal | N | O | F | total |", "|---|---|---|---|---|---|---|---|"]
    for r in m.itertuples():
        lines.append(f"| {r.A} | {r.B} | {r.X} | {r.metal:+.3f} | {r.N:+.3f} | {r.O:+.3f} | {r.F:+.3f} | {r.total:+.3f} |")
    lines += ["\n## Change on replacing the first B-site element by Co\n",
              "| A | substitution | anions | metal | anions' moment | total |", "|---|---|---|---|---|---|"]
    key = m.set_index(["A", "B", "X"])
    for a in A_SITES:
        for b in ("Mn", "Fe"):
            for x in ANIONS:
                if (a, b, x) in key.index and (a, "Co", x) in key.index:
                    d = key.loc[(a, "Co", x)] - key.loc[(a, b, x)]
                    lines.append(f"| {a} | {b} -> Co | {x} | {d.metal:+.3f} | {d.anions:+.3f} | {d.total:+.3f} |")
    write_report(REPORT, "\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
