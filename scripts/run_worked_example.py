"""One substitution inside a full-grid block holdout, predicted by the three models.

The first block design of run_full_grid.py (11 A-site and 11 B-site elements, seeded generator)
hides every composition whose A-site and B-site elements both fall in its two sets. Na is among
its A-site elements and Ag and Nb among its B-site elements, so no calculation combines Na with
either, although each element is computed with the other sites. For the formation-energy response
of replacing Ag by Nb at the Na site, in each of the seven anion sets, the script records the
computed value and the predictions of the descriptor basis, free element effects and the similarity
prior fitted on the training compositions of that design. It also pools every B-site substitution
inside the hidden block, at a fixed A site and anion, to give the errors the example stands for.

Writes reports/worked_example.csv and reports/AUDIT_WORKED_EXAMPLE.md.

Usage:  OPENBLAS_NUM_THREADS=1 python3 scripts/run_worked_example.py
"""

from __future__ import annotations

import itertools
import sys
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))
sys.path.insert(0, str(Path(__file__).resolve().parent))

from prfield.descriptors import elemental as el  # noqa: E402
from prfield.models import hybrid  # noqa: E402
from prfield.models.baselines import NodeModel  # noqa: E402
from prfield.report import write_report  # noqa: E402
from prfield.splits import observation as obs  # noqa: E402

PROP = "heat_of_formation"
SMOOTH = 0.1
A_SITES, B_FROM, B_TO = ("Na",), "Ag", "Nb"
CSV = Path("reports/worked_example.csv")
REPORT = Path("reports/AUDIT_WORKED_EXAMPLE.md")


def main() -> None:
    grid = pd.read_parquet("data/interim/castelli_raw.parquet").reset_index(drop=True)
    a_all, b_all = sorted(grid.site_A.unique()), sorted(grid.site_B.unique())
    rng = np.random.default_rng(0)
    aa = list(rng.choice(a_all, size=11, replace=False))
    bb = list(rng.choice(b_all, size=11, replace=False))
    assert set(A_SITES) <= set(aa) and {B_FROM, B_TO} <= set(bb)
    design = obs.held_out_block(grid, {"A": aa, "B": bb})
    train = design.train_nodes(grid).dropna(subset=[PROP]).reset_index(drop=True)
    desc = {s: el.physical_descriptors(sorted(grid[f"site_{s}"].unique().tolist()),
                                       "element" if s in ("A", "B") else "auto") for s in ("A", "B", "X")}
    basis = NodeModel(desc, PROP, interactions=True).fit(train)
    models = {}
    for tag, g in (("free", 0.0), ("prior", SMOOTH)):
        eff = hybrid.fit_stage1(train, PROP, smooth=g, desc=desc)
        maps, norm = hybrid.fit_stage2(eff, desc)
        models[tag] = hybrid.HybridModel(eff, maps, norm, desc)
    rows = []
    for a in A_SITES:
        for x in sorted(grid.site_X.unique()):
            pair = grid[(grid.site_A == a) & (grid.site_X == x) & grid.site_B.isin([B_FROM, B_TO])]
            src, dst = pair[pair.site_B == B_FROM], pair[pair.site_B == B_TO]
            if len(src) != 1 or len(dst) != 1:
                continue
            rec = {"A": a, "X": x, "computed": float(dst[PROP].iloc[0] - src[PROP].iloc[0]),
                   "basis": float(basis.predict_node(dst)[0] - basis.predict_node(src)[0])}
            for tag, m in models.items():
                rec[tag] = float(m.predict(dst)[0] - m.predict(src)[0])
            rows.append(rec)
    res = pd.DataFrame(rows)
    res.to_csv(CSV, index=False)
    # every B-site substitution inside the hidden block, at a fixed A site and anion
    hid = grid[grid.site_A.isin(aa) & grid.site_B.isin(bb)].dropna(subset=[PROP]).reset_index(drop=True)
    pred = {"basis": basis.predict_node(hid), **{t: m.predict(hid) for t, m in models.items()}}
    key = hid.assign(**pred).set_index(["site_A", "site_X", "site_B"]).sort_index()
    pooled = {k: [] for k in ("computed", "basis", "free", "prior")}
    for (a, x), g in key.groupby(level=[0, 1]):
        g = g.droplevel([0, 1])
        for b, b2 in itertools.combinations(g.index, 2):
            pooled["computed"].append(g.loc[b2, PROP] - g.loc[b, PROP])
            for k in ("basis", "free", "prior"):
                pooled[k].append(g.loc[b2, k] - g.loc[b, k])
    y = np.array(pooled["computed"])
    block = {k: float(np.mean(np.abs(np.array(pooled[k]) - y))) for k in ("basis", "free", "prior")}
    err = {k: float(np.mean(np.abs(res[k] - res.computed))) for k in ("basis", "free", "prior")}
    lines = [f"# Replacing {B_FROM} by {B_TO} inside a block holdout\n",
             "Generated by `scripts/run_worked_example.py`. Formation-energy response (eV/atom) of replacing "
             f"{B_FROM} by {B_TO} at {', '.join(A_SITES)} in each anion set; none of these compositions is in "
             "training.\n", "| A | anion | computed | basis | free effects | prior |", "|---|---|---|---|---|---|"]
    for r in res.itertuples():
        lines.append(f"| {r.A} | {r.X} | {r.computed:+.3f} | {r.basis:+.3f} | {r.free:+.3f} | {r.prior:+.3f} |")
    lines.append("\nMean absolute error: " + ", ".join(f"{k} {v:.3f}" for k, v in err.items()) + " eV/atom.")
    lines.append(f"\nAll {len(y)} B-site substitutions inside the hidden block: mean absolute error "
                 + ", ".join(f"{k} {v:.3f}" for k, v in block.items())
                 + f" eV/atom; basis {block['basis'] / block['free'] - 1:+.0%} and prior "
                 f"{block['prior'] / block['free'] - 1:+.0%} relative to free effects.")
    write_report(REPORT, "\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
