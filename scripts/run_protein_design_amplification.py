"""Design amplification of the additive protein model, on the scale used for the perovskite models.

run_peak_mode_coupling.py measures how much a sampled design amplifies a unit-variance omitted
field into the held-out responses: Gamma = tr(E K), K = G^+ - R F^-1 R, with G the Gram matrix of
the sampled orthonormal ANOVA basis, F that of the complete grid, R the projector onto the
identified subspace and E the mean outer product of the response contrasts with both compositions
hidden. This computes the same quantity for the additive 19 x 19 two-position model. Gamma depends
on the design only, so 200 random masks per n/p replace the protein labels.

Writes reports/protein_design_amplification.csv and reports/AUDIT_PROTEIN_DESIGN_AMPLIFICATION.md.

Usage:  OPENBLAS_NUM_THREADS=1 python3 scripts/run_protein_design_amplification.py
"""

from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
import pandas as pd
import scipy.linalg as la

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))
from prfield.report import write_report  # noqa: E402

REPORT = Path("reports/AUDIT_PROTEIN_DESIGN_AMPLIFICATION.md")
CSV = Path("reports/protein_design_amplification.csv")
PEROVSKITE = Path("reports/peak_mode_coupling/decomposition.csv")
NP_TARGETS = (0.3, 0.5, 0.7, 0.85, 1.0, 1.15, 1.3, 1.6, 2.0, 3.0)
MASKS = 200
M = 19


def main() -> None:
    cells = np.array([(i, j) for i in range(M) for j in range(M)])
    H = la.helmert(M, full=False).T                      # orthonormal sum-to-zero contrasts
    Z = np.column_stack([np.ones(len(cells)) / np.sqrt(len(cells)), H[cells[:, 0]], H[cells[:, 1]]])
    p = Z.shape[1]
    full_inv = 1 / (Z * Z).sum(axis=0)
    index = {tuple(c): k for k, c in enumerate(cells)}
    pairs = [(index[(a, c)], index[(b, c)]) for a in range(M) for b in range(a + 1, M) for c in range(M)]
    pairs += [(index[(c, a)], index[(c, b)]) for a in range(M) for b in range(a + 1, M) for c in range(M)]
    pairs = np.array(pairs)
    rng = np.random.default_rng(0)
    rows = []
    for target in NP_TARGETS:
        n = int(round(target * p))
        for mask_id in range(MASKS):
            train = np.zeros(len(cells), bool)
            train[rng.choice(len(cells), n, replace=False)] = True
            _, sv, Vt = la.svd(Z[train], full_matrices=False)
            keep = sv > sv[0] * 1e-10
            sv, V = sv[keep], Vt[keep].T
            Gplus = (V / sv**2) @ V.T
            Pr = V @ V.T
            K = Gplus - (Pr * full_inv) @ Pr
            held = ~train[pairs[:, 0]] & ~train[pairs[:, 1]]
            D = Z[pairs[held, 1]] - Z[pairs[held, 0]]
            E = D.T @ D / len(D)
            rows.append(dict(target=target, n=n, mask=mask_id, rank=int(keep.sum()), nullity=p - int(keep.sum()),
                             min_positive_g=float(sv.min() ** 2), gamma=float(np.sum(E * K.T))))
    res = pd.DataFrame(rows)
    CSV.parent.mkdir(parents=True, exist_ok=True)
    res.to_csv(CSV, index=False)
    prot = res.groupby("target").agg(gamma=("gamma", "median"), nullity=("nullity", "mean"),
                                     min_g=("min_positive_g", "median"))
    out = ["# Design amplification of the additive protein model\n",
           "_Generated by `scripts/run_protein_design_amplification.py`._ Gamma as in "
           "`run_peak_mode_coupling.py`; 200 random masks of n cells per n/p on a 19 x 19 grid, "
           "37 identified parameters; responses with both cells hidden.\n"]
    per = None
    if PEROVSKITE.exists():
        d = pd.read_csv(PEROVSKITE)
        d = d[d.property == d.property.iloc[0]]
        col = "geometry"
        per = d.pivot_table(index="target", columns="model", values=col, aggfunc="median")
    out.append("| n/p | protein Gamma (median) | protein mean nullity | protein median smallest nonzero g |"
               + ("" if per is None else " perovskite additive | perovskite AX+BX | perovskite all pairs |"))
    out.append("|---|---|---|---|" + ("" if per is None else "---|---|---|"))
    for t, r in prot.iterrows():
        line = f"| {t:g} | {r.gamma:.2f} | {r.nullity:.2f} | {r.min_g:.3f} |"
        if per is not None:
            near = per.index[np.argmin(np.abs(per.index.to_numpy() - t))]
            line += " " + " | ".join(f"{per.loc[near, m]:.2f}" if m in per else "n/a"
                                     for m in ("additive", "AX+BX", "all pairs")) + " |"
        out.append(line)
    write_report(REPORT, "\n".join(out))
    print("\n".join(out))


if __name__ == "__main__":
    main()
