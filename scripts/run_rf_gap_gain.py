"""Where the random forest is more accurate than the shared-trend model for a left-out B-site element.

For each left-out B-site element, both models (fitted as in run_rf_gap_attribution.py) predict the
element's 364 compositions, 52 A-site elements by seven anions. With p0 the shared-trend
prediction, p1 the random-forest prediction, y the computed values and delta = p1 - p0 split into
the four orthogonal parts of a balanced A-by-X field (a constant, a part that changes with the A
site alone, one that changes with the anion alone, one that changes with both jointly), the
reduction in mean squared error is exactly

    MSE(p0) - MSE(p1) = (2/N) sum_k <delta_k, y - (p0 + p1)/2>,

one term per part. The terms are summed over the 52 elements before shares are taken. Next to them
the script records the squared difference of the two predictions in each part, so that
disagreement and gained accuracy can be compared part by part.

Writes reports/rf_gap_gain.csv and reports/AUDIT_RF_GAP_GAIN.md.

Usage:  OPENBLAS_NUM_THREADS=1 python3 scripts/run_rf_gap_gain.py --n-jobs 4
        python3 scripts/run_rf_gap_gain.py --summary-only   (rewrite the report from the CSV)
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import numpy as np
import pandas as pd
from joblib import Parallel, delayed
from sklearn.ensemble import RandomForestRegressor

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))
sys.path.insert(0, str(Path(__file__).resolve().parent))

from prfield.models.semiparametric import SemiparametricBModel, decompose_two_way_field  # noqa: E402
from prfield.report import write_report  # noqa: E402
from run_as_cs_mechanism_audit import descriptor_features  # noqa: E402
from run_rf_gap_attribution import cube_axes, values_to_cube  # noqa: E402
from run_semiparametric_kernel_validation import RF_TREES, TARGETS, descriptors, load_full_grid  # noqa: E402

CSV = Path("reports/rf_gap_gain.csv")
REPORT = Path("reports/AUDIT_RF_GAP_GAIN.md")
PARTS = ("constant", "a_only", "x_only", "joint")


def parts(field: np.ndarray) -> dict[str, np.ndarray]:
    mean, a, x, ax = decompose_two_way_field(field)
    shape = field.shape
    return {"constant": np.full(shape, mean), "a_only": np.broadcast_to(a[:, None], shape),
            "x_only": np.broadcast_to(x[None, :], shape), "joint": ax}


def run_level(frame, desc, prop, level, axes):
    held = axes[1].index(level)
    train = frame[frame.site_B.ne(level)].dropna(subset=[prop]).reset_index(drop=True)
    semi = values_to_cube(frame, SemiparametricBModel.fit(train, prop, desc["B"]).predict(frame), axes)[held]
    x_train, fitted = descriptor_features(train, desc)
    x_full, _ = descriptor_features(frame, desc, fitted)
    forest = RandomForestRegressor(n_estimators=RF_TREES, random_state=0, n_jobs=1)
    rf = values_to_cube(frame, forest.fit(x_train, train[prop].to_numpy(float)).predict(x_full), axes)[held]
    y = values_to_cube(frame, frame[prop].to_numpy(float), axes)[held]
    delta, mid = rf - semi, y - (rf + semi) / 2
    rec = {"property": prop, "held_level": level,
           "mse_shared_trend": float(np.mean((y - semi) ** 2)), "mse_forest": float(np.mean((y - rf) ** 2))}
    for name, part in parts(delta).items():
        rec[f"gain_{name}"] = float(2 * np.mean(part * mid))
        rec[f"disagreement_{name}"] = float(np.mean(part ** 2))
    rec["identity_error"] = rec["mse_shared_trend"] - rec["mse_forest"] - sum(rec[f"gain_{k}"] for k in PARTS)
    return rec


def write_summary(res: pd.DataFrame) -> None:
    lines = ["# Where the random forest gains accuracy over the shared-trend model\n",
             "Generated by `scripts/run_rf_gap_gain.py`. For each left-out B-site element the reduction in mean "
             "squared error over its 364 compositions is split exactly into four parts; terms are summed over "
             "the 52 elements. `disagreement` is the share of the squared difference between the two "
             "predictions in each part.\n",
             "| property | MSE reduction | quantity | constant | A site only | anion only | both jointly |",
             "|---|---|---|---|---|---|---|"]
    for prop, g in res.groupby("property"):
        gain = np.array([g[f"gain_{k}"].sum() for k in PARTS])
        dis = np.array([g[f"disagreement_{k}"].sum() for k in PARTS])
        total = g.mse_shared_trend.sum() - g.mse_forest.sum()
        lines.append(f"| {prop} | {total / len(g):+.4g} per element | share of gain | "
                     + " | ".join(f"{100 * v / gain.sum():.0f}%" for v in gain) + " |")
        lines.append(f"| | | share of disagreement | " + " | ".join(f"{100 * v / dis.sum():.0f}%" for v in dis) + " |")
        lines.append(f"| | | elements with a positive term | "
                     + " | ".join(f"{int((g[f'gain_{k}'] > 0).sum())}/{len(g)}" for k in PARTS) + " |")
    lines.append(f"\nLargest identity error: {res.identity_error.abs().max():.2e}.")
    write_report(REPORT, "\n".join(lines))
    print("\n".join(lines))


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--n-jobs", type=int, default=4)
    ap.add_argument("--summary-only", action="store_true", help="rewrite the report from the existing CSV")
    args = ap.parse_args()
    if args.summary_only:
        write_summary(pd.read_csv(CSV))
        return
    frame = load_full_grid()
    desc = descriptors(frame)
    axes = cube_axes(frame)
    rows = Parallel(n_jobs=args.n_jobs, verbose=5)(
        delayed(run_level)(frame, desc, prop, level, axes) for prop in TARGETS for level in axes[1])
    res = pd.DataFrame(rows)
    res.to_csv(CSV, index=False)
    write_summary(res)


if __name__ == "__main__":
    main()
