"""Which elements carry the site-effect variance that ten elemental descriptors cannot represent.

On the complete 52 x 52 x 7 Castelli grid every site effect is exact (the mean over the element's
compositions minus the grand mean). Projecting the effects of one site onto the span of a constant
and the ten standardised descriptors of scripts/run_descriptor_ladder.py leaves one residual per
element; its square over the sum of squares is that element's share of the variance outside the
span. The same projection is repeated for volume.

Each element is also left out in turn and its exact effect predicted from the other elements by
the linear map and by the radial-kernel map of scripts/run_effect_map.py. For the eight A-site
elements the main text names, the ratio of their summed squared errors says how much of what lies
outside the span a nonlinear function of the same descriptors recovers.

Writes reports/descriptor_residuals.csv and reports/AUDIT_DESCRIPTOR_RESIDUALS.md.

Usage:  PYTHONPATH=src python3 scripts/run_descriptor_residuals.py
"""

from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))
sys.path.insert(0, str(Path(__file__).resolve().parent))

from prfield.models import hybrid  # noqa: E402
from prfield.report import write_report  # noqa: E402
from run_descriptor_ladder import paper_matrix  # noqa: E402
from run_effect_map import LAM2, _std, pick_gamma  # noqa: E402

REPORT = Path("reports/AUDIT_DESCRIPTOR_RESIDUALS.md")
CSV = Path("reports/descriptor_residuals.csv")
PROPS = ("heat_of_formation", "volume_per_fu")
# A-site elements named in the main text: size extremes and lone-pair cations
NAMED_A = ("B", "Cs", "Rb", "Li", "Pb", "Bi", "Sn", "Ge")


def residuals(M: np.ndarray, v: np.ndarray) -> np.ndarray:
    sd = M.std(0)
    Z = (M - M.mean(0)) / np.where(sd > 0, sd, 1.0)
    P = np.hstack([np.ones((len(Z), 1)), Z])
    return v - P @ np.linalg.lstsq(P, v, rcond=None)[0]


def loo_errors(M: np.ndarray, y: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
    """Leave-one-element-out errors of the linear and the radial-kernel map."""
    lin, rad = np.empty(len(y)), np.empty(len(y))
    for i in range(len(y)):
        keep = [k for k in range(len(y)) if k != i]
        Z = _std(M, keep)
        Ptr = np.hstack([np.ones((len(keep), 1)), Z[keep]])
        lin[i] = y[i] - float(np.hstack([[1.0], Z[i]]) @ hybrid._ridge(Ptr, y[keep], LAM2))
        g = pick_gamma(Z, y, keep)
        K = np.exp(-g * ((Z[keep][:, None] - Z[keep][None]) ** 2).sum(-1))
        a = np.linalg.lstsq(K + LAM2 * np.eye(len(K)), y[keep], rcond=None)[0]
        kk = np.exp(-g * ((Z[[i]][:, None] - Z[keep][None]) ** 2).sum(-1))
        rad[i] = y[i] - float((kk @ a)[0])
    return lin, rad


def main() -> None:
    df = pd.read_parquet("data/interim/castelli_raw.parquet")
    rows = []
    for prop in PROPS:
        g = df.dropna(subset=[prop])
        mu = g[prop].mean()
        for site in ("A", "B"):
            eff = g.groupby(f"site_{site}")[prop].mean() - mu
            labels = sorted(eff.index)
            v = eff.reindex(labels).to_numpy(float)
            M = paper_matrix(labels)
            r = residuals(M, v)
            share = r**2 / np.sum(r**2)
            lin, rad = loo_errors(M, v)
            for lab, e, res, s, li, ra in zip(labels, v, r, share, lin, rad):
                rows.append({"property": prop, "site": site, "element": lab, "effect": e,
                             "residual": res, "share_outside_span": s,
                             "loo_linear": li, "loo_radial": ra})
    d = pd.DataFrame(rows)
    CSV.parent.mkdir(parents=True, exist_ok=True)
    d.to_csv(CSV, index=False)

    out = ["# Elements outside the descriptor span\n",
           "_Generated by `scripts/run_descriptor_residuals.py`._ Exact site effects on the complete "
           "grid, projected onto a constant and the ten standardised descriptors. Share: the element's "
           "squared residual over the sum for its site.\n"]
    for (prop, site), g in d.groupby(["property", "site"], sort=False):
        top = g.sort_values("share_outside_span", ascending=False).head(12)
        out.append(f"## {prop.replace('_', ' ')}, {site} site\n")
        out.append("| element | effect | residual | share |")
        out.append("|---|---:|---:|---:|")
        for t in top.itertuples():
            out.append(f"| {t.element} | {t.effect:+.3f} | {t.residual:+.3f} | {100 * t.share_outside_span:.1f}% |")
        out.append(f"\nTop ten together: {100 * top.share_outside_span.head(10).sum():.1f}%.\n")
    out.append("## Linear and radial-kernel maps, A-site elements named in the main text\n")
    out.append("Leave-one-element-out squared error of the radial-kernel map over that of the linear "
               "map, summed over the elements in each row.\n")
    out.append("| property | elements | share outside span | radial / linear | radial lower |")
    out.append("|---|---|---:|---:|---:|")
    for prop in PROPS:
        a = d[(d.property == prop) & (d.site == "A")].set_index("element")
        for name, g in ((", ".join(NAMED_A), a.loc[list(NAMED_A)]), ("all 52", a)):
            ratio = float((g.loo_radial**2).sum() / (g.loo_linear**2).sum())
            lower = int((g.loo_radial.abs() < g.loo_linear.abs()).sum())
            out.append(f"| {prop.replace('_', ' ')} | {name} | {100 * g.share_outside_span.sum():.1f}% | "
                       f"{ratio:.3f} | {lower}/{len(g)} |")
    write_report(REPORT, "\n".join(out))
    print("\n".join(out))


if __name__ == "__main__":
    main()
