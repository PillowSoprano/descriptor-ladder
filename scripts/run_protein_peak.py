"""Is the additive protein model really free of an interpolation peak?

run_protein_replication.py samples coverage at 3, 5, 8, 12, 20, 35, 50 and 75%, which leaves no
point between n/p = 0.78 and 1.19, where the additive materials model peaks. This refits the same
weakly penalised free effects (lambda = 1e-3, as in the replication) and the minimum-norm version
on the same 120 grids at coverages placed densely around n = p, scoring responses whose two
compositions are both hidden.

Writes reports/protein_peak.csv and reports/AUDIT_PROTEIN_PEAK.md.

Usage:  OPENBLAS_NUM_THREADS=1 python3 scripts/run_protein_peak.py
"""

from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent))

import run_protein_replication as rp  # noqa: E402
from prfield.report import write_report  # noqa: E402

REPORT = Path("reports/AUDIT_PROTEIN_PEAK.md")
CSV = Path("reports/protein_peak.csv")
NP_TARGETS = (0.3, 0.5, 0.7, 0.85, 1.0, 1.15, 1.3, 1.6, 2.0, 3.0)
SEEDS = tuple(range(5))


def fit(i1, i2, y, n, lam):
    rp.LAM = lam
    return rp.fit_free(i1, i2, y, n, n)


def main() -> None:
    d = pd.read_csv(rp.RAW, sep="\t")
    db = d[d["num_mutations"] == 2].copy()
    parts = db["variant"].str.split(",", expand=True)
    db["p1"] = parts[0].str.extract(r"(\d+)").astype(int)
    db["a1"] = parts[0].str[-1]
    db["p2"] = parts[1].str.extract(r"(\d+)").astype(int)
    db["a2"] = parts[1].str[-1]
    counts = db.groupby(["p1", "p2"]).size()
    full = counts[counts == 361].index.tolist()
    rng = np.random.default_rng(0)
    chosen = [full[i] for i in rng.choice(len(full), min(rp.N_PAIRS, len(full)), replace=False)]

    n = 19
    p_free = 1 + 2 * (n - 1)
    cells = np.array([(i, j) for i in range(n) for j in range(n)])
    rows = []
    for pr in chosen:
        g = db[(db["p1"] == pr[0]) & (db["p2"] == pr[1])]
        M = g.pivot_table(index="a1", columns="a2", values="score")
        if M.isna().any().any() or M.shape != (19, 19):
            continue
        A = M.to_numpy(float)
        y_all = A[cells[:, 0], cells[:, 1]]
        for target in NP_TARGETS:
            frac = target * p_free / len(cells)
            for seed in SEEDS:
                r = np.random.default_rng(pr[0] * 100003 + pr[1] * 1009 + seed * 31
                                          + int(frac * 10000))
                obs = r.random(len(cells)) < frac
                if obs.sum() < 8:
                    continue
                held = ~obs
                hidx = np.flatnonzero(held)
                hs = set(map(tuple, cells[hidx]))
                pairs = [((a, c), (b, c)) for a in range(n) for b in range(a + 1, n)
                         for c in range(n) if (a, c) in hs and (b, c) in hs]
                pairs += [((c, a), (c, b)) for a in range(n) for b in range(a + 1, n)
                          for c in range(n) if (c, a) in hs and (c, b) in hs]
                pairs = np.array(pairs)
                if len(pairs) > 4000:
                    pairs = pairs[r.choice(len(pairs), 4000, replace=False)]
                t = A[pairs[:, 1, 0], pairs[:, 1, 1]] - A[pairs[:, 0, 0], pairs[:, 0, 1]]
                i1, i2, y = cells[obs, 0], cells[obs, 1], y_all[obs]
                rec = {"pair": f"{pr[0]}-{pr[1]}", "target": target, "frac": frac,
                       "seed": seed, "n_obs": int(obs.sum()), "n_over_p": obs.sum() / p_free}
                for tag, lam in (("weak", 1e-3), ("min_norm", 1e-8)):
                    b = fit(i1, i2, y, n, lam)
                    pred = (rp.pred_free(b, pairs[:, 1, 0], pairs[:, 1, 1], n)
                            - rp.pred_free(b, pairs[:, 0, 0], pairs[:, 0, 1], n))
                    rec[tag] = float(np.mean(np.abs(t - pred)))
                rows.append(rec)
    res = pd.DataFrame(rows)
    CSV.parent.mkdir(parents=True, exist_ok=True)
    res.to_csv(CSV, index=False)
    per_grid = res.groupby(["pair", "target"])[["weak", "min_norm", "n_over_p"]].median()
    curve = per_grid.groupby("target").median()
    out = ["# Protein free effects near n = p\n",
           "_Generated by `scripts/run_protein_peak.py`._ 120 GB1 grids, five seeds per "
           "coverage, responses with both compositions hidden; median over seeds within a grid, "
           "then over grids.\n",
           "| target n/p | realised n/p | weak ridge (1e-3) | minimum norm |", "|---|---|---|---|"]
    for t, r in curve.iterrows():
        out.append(f"| {t:g} | {r.n_over_p:.2f} | {r.weak:.4f} | {r.min_norm:.4f} |")
    for col in ("weak", "min_norm"):
        u = curve[col].to_numpy()
        prior_min = np.minimum.accumulate(np.r_[np.inf, u[:-1]])
        rise = 100 * (u / prior_min - 1)
        k = int(np.nanargmax(rise))
        out.append(f"\nLargest rise of error as data are added ({col}): {max(rise[k], 0):+.1f}% "
                   f"at n/p = {curve.index[k]:g}.")
    write_report(REPORT, "\n".join(out))
    print("\n".join(out))


if __name__ == "__main__":
    main()
