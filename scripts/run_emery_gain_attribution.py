"""Where the similarity prior's gain sits on the Emery-Wolverton subgrids, block by block.

The coverage sweep of run_emery_replication.py is repeated at 5, 20, 50 and 90% coverage on the
same seven 37 x 37 subgrids and seeds 0 to 2, with the same random designs, inner selection and
both-hidden test responses. For the tuned ridge (prediction p0) and the real-descriptor prior (p1),
the reduction in mean squared error, (2/n) sum_b <delta_b, y - (p0 + p1)/2> with
delta_b the block-b part of p1 - p0, is split exactly into one term per block of effects, as in
Table S11. Shares are taken after summing each term over the 21 designs at one coverage.

A single-anion 37 x 37 subgrid has 1 + 36 + 36 + 36 x 36 = 1,369 identified parameters for 1,369
compositions, so n/p stays below one at every coverage.

Writes reports/emery_gain_attribution.csv and reports/AUDIT_EMERY_GAIN_ATTRIBUTION.md.

Usage:  OPENBLAS_NUM_THREADS=1 VECLIB_MAXIMUM_THREADS=1 python3 scripts/run_emery_gain_attribution.py --n-jobs 4
        python3 scripts/run_emery_gain_attribution.py --summary-only   (rewrite the report from the CSV)
"""

from __future__ import annotations

import argparse
import sys
import time
from pathlib import Path

import numpy as np
import pandas as pd
from joblib import Parallel, delayed

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))
sys.path.insert(0, str(Path(__file__).resolve().parent))

import run_regularization_baselines as mh  # noqa: E402
from emery_grid import load_emery_grid  # noqa: E402
from prfield.graph.typed_graph import accepted, build_edges  # noqa: E402
from prfield.models import hybrid  # noqa: E402
from prfield.report import write_report  # noqa: E402
from prfield.schema import SITES  # noqa: E402
from prfield.splits import observation as obs  # noqa: E402
from run_emery_replication import POLICY, PROPS, descriptors, subgrids  # noqa: E402

COVERAGES, SEEDS = (0.05, 0.20, 0.50, 0.90), (0, 1, 2)
CSV = Path("reports/emery_gain_attribution.csv")
REPORT = Path("reports/AUDIT_EMERY_GAIN_ATTRIBUTION.md")
BLOCKS = {"A": "A-site effects", "B": "B-site effects", "AB": "A-B interactions"}


def panel_task(grid, panel, a_levels, b_levels):
    sub = grid[grid.site_A.isin(a_levels) & grid.site_B.isin(b_levels)].reset_index(drop=True)
    levels = {s: sorted(sub[f"site_{s}"].unique().tolist()) for s in SITES}
    desc = descriptors(sub)
    template, slices = hybrid._design_and_slices(sub.iloc[:1], levels)
    metrics = {"descriptor_metric": mh.metric_matrix(desc, levels, slices, template.shape[1])}
    node_index = sub.set_index("sample_id")
    n_params = 1 + sum(len(levels[s]) - 1 for s in ("A", "B")) + (len(levels["A"]) - 1) * (len(levels["B"]) - 1)
    rows = []
    for prop in PROPS:
        edges = accepted(build_edges(sub, prop, POLICY)).reset_index(drop=True)
        for cov in COVERAGES:
            for seed in SEEDS:
                split = obs.random_nodes(sub, cov, seed=seed)
                train = split.train_nodes(sub).dropna(subset=[prop]).reset_index(drop=True)
                test = mh.edge_subset(edges, split.held_out_ids, both_hidden=True)
                betas = {}
                for model in ("ordinary_ridge", "descriptor_metric"):
                    option, _, _ = mh.select_candidate(train, prop, levels, edges, node_index, model, metrics, seed)
                    betas[model] = np.asarray(mh.fit_candidate(train, prop, levels, model, option, metrics), float).ravel()
                src = node_index.loc[test["src"]].reset_index()
                dst = node_index.loc[test["dst"]].reset_index()
                d = hybrid._design_and_slices(dst, levels)[0] - hybrid._design_and_slices(src, levels)[0]
                y = test["delta"].to_numpy(float)
                p0, p1 = d @ betas["ordinary_ridge"], d @ betas["descriptor_metric"]
                change = betas["descriptor_metric"] - betas["ordinary_ridge"]
                mid = y - (p0 + p1) / 2
                rec = {"panel": panel, "property": prop, "coverage": cov, "seed": seed, "n_train": len(train),
                       "n_over_p": len(train) / n_params, "n_test": len(test),
                       "mse_ridge": float(np.mean((y - p0) ** 2)), "mse_prior": float(np.mean((y - p1) ** 2)),
                       "mae_ridge": float(np.mean(np.abs(y - p0))), "mae_prior": float(np.mean(np.abs(y - p1)))}
                for key, sl in slices.items():
                    delta_b = d[:, sl] @ change[sl]
                    rec[f"term_{''.join(key)}"] = float(2 * np.mean(delta_b * mid))
                rows.append(rec)
    return rows


def write_summary(res: pd.DataFrame) -> None:
    terms = [c for c in res.columns if c.startswith("term_")]
    lines = ["# Where the similarity prior's gain sits on the Emery-Wolverton subgrids\n",
             "Generated by `scripts/run_emery_gain_attribution.py`. Each term is one block's exact share of the "
             "reduction in mean squared error, prior against tuned ridge, on responses with neither composition "
             "computed, summed over seven subgrids and three seeds. n/p uses the 1,369 identified parameters of "
             "the pair model on a 37 x 37 single-anion subgrid.\n",
             "| property | coverage | n/p | median gain (MAE) | A-site effects | B-site effects | A-B interactions | other |",
             "|---|---|---|---|---|---|---|---|"]
    for (prop, cov), g in res.groupby(["property", "coverage"]):
        total = g[terms].sum().sum()
        share = {k: g[f"term_{k}"].sum() / total for k in BLOCKS}
        other = 1 - sum(share.values())
        per_panel = g.groupby("panel")[["mae_ridge", "mae_prior"]].mean()
        gain = float((1 - per_panel.mae_prior / per_panel.mae_ridge).median())
        lines.append(f"| {prop} | {cov:.0%} | {g.n_over_p.median():.2f} | {gain:+.1%} | {share['A']:.0%} | "
                     f"{share['B']:.0%} | {share['AB']:.0%} | {other:.0%} |")
    check = (res.mse_ridge - res.mse_prior - res[terms].sum(axis=1)).abs().max()
    lines.append(f"\nLargest gap between the summed terms and the MSE reduction: {check:.2e}.")
    write_report(REPORT, "\n".join(lines))
    print("\n".join(lines))


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--n-jobs", type=int, default=4)
    ap.add_argument("--summary-only", action="store_true", help="rewrite the report from the existing CSV")
    args = ap.parse_args()
    if args.summary_only:
        write_summary(pd.read_csv(CSV))
        return
    t0 = time.time()
    grid = load_emery_grid()
    out = Parallel(n_jobs=args.n_jobs, verbose=5)(delayed(panel_task)(grid, *p) for p in subgrids(grid))
    res = pd.DataFrame([r for rows in out for r in rows])
    res.to_csv(CSV, index=False)
    write_summary(res)
    print(f"done in {(time.time() - t0) / 60:.0f} minutes")


if __name__ == "__main__":
    main()
